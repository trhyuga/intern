// 台詞を選ぶ
function line(g, kind, ctx = {}) {
  if (!g) return '';
  let pool = null;
  const sp = SPECIAL_LINES[g.name];
  if (sp && sp[kind]) pool = sp[kind];
  else if (g.isLord && LORD_LINES[kind] && Math.random() < 0.7) pool = LORD_LINES[kind];
  else {
    const tbl = LINES[kind];
    if (tbl) {
      if (Array.isArray(tbl)) pool = tbl;
      else {
        // 性格の台詞と共通の台詞を混ぜる（性格の台詞を出やすく）
        const own = [];
        (g.traits || []).forEach(t => { if (tbl[t]) own.push(...tbl[t]); });
        pool = own.length && Math.random() < 0.75 ? own : (tbl._ || own);
      }
    }
  }
  if (!pool || !pool.length) pool = (LINES.success._);
  let s = Array.isArray(pool) ? pick(pool) : pool;
  const v = VOICE[g.name] || {};
  const I = v.I || (g.female ? 'わたくし' : g.isLord ? '我' : (g.war >= 85 && (g.traits || []).some(t => t === '猪突' || t === '剛勇')) ? '俺' : g.war > g.int ? '拙者' : '私');
  let lordName = '殿';
  try { if (g.faction >= 0 && G && G.factions[g.faction]) lordName = Game.lordOf(g.faction).name; } catch (e) {}
  const you = v.you && (!v.youIf || v.youIf === lordName) ? v.you : '殿';
  return s.replace(/\{I\}/g, I).replace(/\{you\}/g, you).replace(/\{lord\}/g, lordName).replace(/\{foe\}/g, ctx.foe || '貴様');
}
